import jwt from 'jsonwebtoken';
import { corsHeaders } from './security.js';

const json = (body, status = 200, headers = {}) => new Response(JSON.stringify(body), {
  status,
  headers: { 'content-type': 'application/json; charset=utf-8', ...headers },
});

function authenticatedEmail(request, env) {
  const authorization = request.headers.get('authorization') || request.headers.get('Authorization') || '';
  const token = authorization.startsWith('Bearer ') ? authorization.slice(7).trim() : '';
  const secret = typeof env.JWT_SECRET === 'string' ? env.JWT_SECRET.trim() : '';
  if (!token || !secret) return '';
  try {
    const payload = jwt.verify(token, secret);
    return typeof payload?.user?.email === 'string' ? payload.user.email.trim().toLowerCase() : '';
  } catch { return ''; }
}

async function connectDatabase(env) {
  const connectionString = env.HYPERDRIVE?.connectionString || env.DATABASE_URL || '';
  if (!connectionString) throw new Error('Database connection is not configured.');
  const { Client } = await import('pg');
  const client = new Client({ connectionString, connectionTimeoutMillis: 8000, query_timeout: 10000 });
  await client.connect();
  return client;
}

// Keep first use self-provisioning, matching the Worker's existing push-token
// table setup; the checked-in Supabase migration remains the canonical schema.
async function ensureCollectionTables(client) {
  await client.query(`CREATE TABLE IF NOT EXISTS public.bookmark_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email TEXT NOT NULL,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`);
  await client.query('CREATE UNIQUE INDEX IF NOT EXISTS bookmark_collections_user_name_idx ON public.bookmark_collections (LOWER(user_email), LOWER(name))');
  await client.query('CREATE INDEX IF NOT EXISTS bookmark_collections_user_idx ON public.bookmark_collections (LOWER(user_email), created_at)');
  await client.query(`CREATE TABLE IF NOT EXISTS public.bookmark_collection_items (
    collection_id BIGINT NOT NULL REFERENCES public.bookmark_collections(id) ON DELETE CASCADE,
    user_email TEXT NOT NULL,
    item_kind TEXT NOT NULL CHECK (item_kind IN ('post', 'sermon')),
    item_id BIGINT NOT NULL CHECK (item_id > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (collection_id, item_kind, item_id)
  )`);
  await client.query('CREATE INDEX IF NOT EXISTS bookmark_collection_items_user_idx ON public.bookmark_collection_items (LOWER(user_email), collection_id)');
}

function parseSavedId(value) {
  const raw = String(value || '');
  const match = /^(p|s):(\d+)$/.exec(raw);
  if (!match) return null;
  const id = Number(match[2]);
  if (!Number.isSafeInteger(id) || id <= 0) return null;
  return { kind: match[1] === 'p' ? 'post' : 'sermon', id, feedId: raw };
}

export async function handleBookmarkCollections(request, env, url) {
  if (!url.pathname.startsWith('/api/feed/collections')) return null;
  const headers = corsHeaders(request, env);
  if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers });
  const email = authenticatedEmail(request, env);
  if (!email) return json({ error: 'Sign in required to manage bookmark collections.' }, 401, headers);

  let client;
  try {
    client = await connectDatabase(env);
    await ensureCollectionTables(client);

    if (url.pathname === '/api/feed/collections' && request.method === 'GET') {
      const [collectionRows, itemRows] = await Promise.all([
        client.query(`SELECT c.id::text AS id, c.name, c.created_at,
          COUNT(ci.item_id)::int AS item_count
          FROM public.bookmark_collections c
          LEFT JOIN public.bookmark_collection_items ci
            ON ci.collection_id = c.id AND LOWER(ci.user_email) = LOWER(c.user_email)
          WHERE LOWER(c.user_email) = LOWER($1)
          GROUP BY c.id
          ORDER BY c.created_at ASC, c.id ASC`, [email]),
        client.query(`SELECT ci.collection_id::text AS collection_id, ci.item_kind, ci.item_id
          FROM public.bookmark_collection_items ci
          JOIN public.bookmark_collections c ON c.id = ci.collection_id
          WHERE LOWER(ci.user_email) = LOWER($1) AND LOWER(c.user_email) = LOWER($1)
            AND ((ci.item_kind = 'post' AND EXISTS (
              SELECT 1 FROM public.feed_post_saves s WHERE s.post_id = ci.item_id AND LOWER(s.user_email) = LOWER($1)
            )) OR (ci.item_kind = 'sermon' AND EXISTS (
              SELECT 1 FROM public.feed_saves s WHERE s.sermon_id = ci.item_id AND LOWER(s.user_email) = LOWER($1)
            )))`, [email]),
      ]);
      const memberships = {};
      for (const row of itemRows.rows) {
        const feedId = `${row.item_kind === 'post' ? 'p' : 's'}:${row.item_id}`;
        (memberships[feedId] ||= []).push(String(row.collection_id));
      }
      const collections = collectionRows.rows.map((row) => ({
        id: String(row.id), name: row.name, itemCount: Number(row.item_count || 0),
      }));
      return json({ collections, memberships }, 200, headers);
    }

    if (url.pathname === '/api/feed/collections' && request.method === 'POST') {
      const body = await request.json().catch(() => null);
      const name = typeof body?.name === 'string' ? body.name.trim().replace(/[<>]/g, '').slice(0, 40) : '';
      if (!name) return json({ error: 'Enter a collection name.' }, 400, headers);
      try {
        const result = await client.query(
          'INSERT INTO public.bookmark_collections (user_email,name) VALUES ($1,$2) RETURNING id::text AS id,name,created_at',
          [email, name],
        );
        const row = result.rows[0];
        return json({ collection: { id: String(row.id), name: row.name, itemCount: 0 } }, 201, headers);
      } catch (error) {
        if (error?.code === '23505') return json({ error: 'A collection with that name already exists.' }, 409, headers);
        throw error;
      }
    }

    const itemRoute = /^\/api\/feed\/collections\/(\d+)\/items$/.exec(url.pathname);
    const collectionRoute = /^\/api\/feed\/collections\/(\d+)$/.exec(url.pathname);
    if (collectionRoute && request.method === 'DELETE') {
      const result = await client.query('DELETE FROM public.bookmark_collections WHERE id=$1 AND LOWER(user_email)=LOWER($2) RETURNING id', [collectionRoute[1], email]);
      if (!result.rows.length) return json({ error: 'Collection not found.' }, 404, headers);
      return json({ status: 'ok' }, 200, headers);
    }
    if (itemRoute && ['PUT', 'DELETE'].includes(request.method)) {
      const body = await request.json().catch(() => null);
      const item = parseSavedId(body?.postId);
      if (!item) return json({ error: 'A valid saved post is required.' }, 400, headers);
      const collection = await client.query('SELECT id FROM public.bookmark_collections WHERE id=$1 AND LOWER(user_email)=LOWER($2) LIMIT 1', [itemRoute[1], email]);
      if (!collection.rows.length) return json({ error: 'Collection not found.' }, 404, headers);
      if (request.method === 'PUT') {
        const savedTable = item.kind === 'post' ? 'public.feed_post_saves' : 'public.feed_saves';
        const idColumn = item.kind === 'post' ? 'post_id' : 'sermon_id';
        const saved = await client.query(`SELECT 1 FROM ${savedTable} WHERE ${idColumn}=$1 AND LOWER(user_email)=LOWER($2) LIMIT 1`, [item.id, email]);
        if (!saved.rows.length) return json({ error: 'Save this post before adding it to a collection.' }, 409, headers);
        await client.query(`INSERT INTO public.bookmark_collection_items (collection_id,user_email,item_kind,item_id)
          VALUES ($1,$2,$3,$4) ON CONFLICT (collection_id,item_kind,item_id) DO NOTHING`, [itemRoute[1], email, item.kind, item.id]);
      } else {
        await client.query('DELETE FROM public.bookmark_collection_items WHERE collection_id=$1 AND LOWER(user_email)=LOWER($2) AND item_kind=$3 AND item_id=$4', [itemRoute[1], email, item.kind, item.id]);
      }
      return json({ status: 'ok' }, 200, headers);
    }
    return json({ error: 'Bookmark collection route not found.' }, 404, headers);
  } catch (error) {
    console.error('[worker] bookmark collections API failed', { message: error?.message, code: error?.code });
    return json({ error: 'Unable to sync bookmark collections right now.' }, 500, headers);
  } finally {
    if (client) await client.end().catch(() => {});
  }
}
